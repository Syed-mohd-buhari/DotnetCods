--------------------- ORGANISATION TABLE ONE TIME TABLE POPULATION 
TRUNCATE TABLE ORGANISATION;
COMMIT;

INSERT INTO ORGANISATION (MAINORGANISATIONID,PRACTICEID,VERTICALID,SUBDOMAINRESPONSIBLEID,CONTACTID,CREATIONUSER,MODIFICATIONUSER)
SELECT  M.MAINORGANISATIONID,    P.PRACTICEID,    V.VERTICALRESPONSIBLEID,1,1,1,1
FROM VERTICALRESPONSIBLES V CROSS JOIN MAINORGANISATION M CROSS JOIN PRACTICE P
WHERE M.MAINORGANISATIONDESCRIPTION ='NSE'
AND P.PRACTICEDESCRIPTION  = 'C' || CHR(38) || 'S';

COMMIT;

 -------------------------- VERTICAL ASSIGN TO USER
CREATE TABLE ASPNETUSERROLES_BACKUP AS SELECT * FROM ASPNETUSERROLES;

INSERT INTO aspnetuserverticals (USERID, ORGANISATIONID,CREATIONUSER,MODIFICATIONUSER)
SELECT DISTINCT r1.USERID, org.ORGANISATIONID, 1 as CREATIONUSER, 1 as MODIFICATIONUSER
FROM aspnetuserroles r1 
join verticalresponsibles v1 on v1.VERTICALRESPONSIBLEID = r1.VERTICALRESPONSIBLEID
Join ORGANISATION org on org.VERTICALID = r1.VERTICALRESPONSIBLEID and org.VERTICALID is not null
WHERE NOT EXISTS (
SELECT 1  FROM aspnetuserverticals uo  WHERE uo.USERID = r1.USERID  AND uo.ORGANISATIONID = org.ORGANISATIONID );

COMMIT; 


