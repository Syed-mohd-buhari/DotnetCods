-------------- UPDATE SUBDOMAINRESPONSIBLE TO USER TABLE

MERGE INTO ASPNETUSERS u USING ( SELECT * FROM (  SELECT org.*, ROW_NUMBER() OVER (
PARTITION BY CONTACTID  ORDER BY SUBDOMAINRESPONSIBLEID DESC ) rn  FROM ORGANISATION org )  WHERE rn = 1 ) org ON (org.CONTACTID = u.ID)
WHEN MATCHED THEN
UPDATE SET 
    u.SUBDOMAINRESPONSIBLEID = org.SUBDOMAINRESPONSIBLEID,
    u.ISSUBDOMAINSPOC       = org.ISSUBDOMAINSPOC,
    u.ISEDUSPOC             = org.ISEDUSPOC,
    u.ISDESIGNCONTACT       = org.ISDESIGNCONTACT;
	
COMMIT;

