--INSERT FOR ASPNETROLES BY LCMENGINEERING

INSERT INTO ASPNETUSERROLES (USERID,ROLEID,OPCOID,VERTICALRESPONSIBLEID)		
		SELECT USERID,ROLEID,OPCOID,VERTICALRESPONSIBLEID FROM
    (SELECT DISTINCT USR.ID USERID,1 ROLEID,LCM.OPCOID OPCOID,
    V.VERTICALRESPONSIBLEID VERTICALRESPONSIBLEID
    FROM
             LCMENGINEERINGEDUSPOC STSDS
        JOIN SUBDOMAINSPOCS       SDS ON SDS.SUBDOMAINSPOCID = STSDS.SUBDOMAINSPOCID
        JOIN LCMENGINEERING LCM ON  (STSDS.LCMENGEENERINGID = LCM.LCMENGINEERINGID)
        join OPCOS OP ON (LCM.OPCOID = OP.OPCOID AND UPPER(OP.OPCO) NOT IN ('ZZZ')) 
        JOIN DESIGNCOMPONENTS DC ON (LCM.DESIGNCOMPONENTID = DC.DESIGNCOMPONENTID)
        JOIN SYSTEMTYPES         ST ON DC.SYSTEMTYPEID = ST.SYSTEMTYPEID
        JOIN ASPNETUSERS USR ON upper(regexp_replace(USR.email,' ',''))  = upper(regexp_replace(SDS.SUBDOMAINSPOC,' ','')) 
        JOIN VERTICALRESPONSIBLES V ON ST.VERTICALRESPONSIBLEID = V.VERTICALRESPONSIBLEID)
        WHERE (USERID,ROLEID,OPCOID,VERTICALRESPONSIBLEID) NOT IN (SELECT DISTINCT USERID,ROLEID,OPCOID,VERTICALRESPONSIBLEID FROM ASPNETUSERROLES);
		COMMIT;


