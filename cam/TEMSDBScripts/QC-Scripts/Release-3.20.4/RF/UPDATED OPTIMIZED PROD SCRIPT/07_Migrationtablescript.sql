            lsp.NTKELEMENTASPLNEDUSPOCID,UR.ID
        FROM
                 NETWORKELEMENTASPLANNEDEDUSPOC_MIGTEMP lsp
            JOIN subdomainspocs sp ON upper(regexp_replace(lsp.SubDomainSPOC,' ','')) = upper(regexp_replace(sp.SubDomainSPOC,' ',''))
            JOIN (SELECT * FROM aspnetusers where id not in
(select id from (SELECT id ,EMAIL,ROW_NUMBER()OVER(PARTITION BY upper(regexp_replace(email,' ','')) ORDER BY ID ASC) rt
FROM aspnetusers) where rt ^=1))    ur ON upper(regexp_replace(sp.SUBDOMAINSPOC,' ','')) = upper(regexp_replace(ur.email,' ',''))
         ) SRC ON (TGT.NTKELEMENTASPLNEDUSPOCID = SRC.NTKELEMENTASPLNEDUSPOCID)
         WHEN MATCHED THEN UPDATE SET TGT.ASPNETUSERID = SRC.ID;
		 
