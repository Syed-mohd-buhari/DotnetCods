--INSERT  FOR MIG TABLE  HARDWAREDESIGNCONTANCT

INSERT INTO MajorHWDesignContact_MIGTEMP (Systemtypeid,MajorHWBUILDID,DesignContact,ASPNETUSERID,VerticalResponsible)
Select Distinct st.SystemTypeId, MH.MAJORHARDWAREID, USR.EMAIL as Contact_ID, USR.ID, V.VerticalResponsible
from SystemTypes st JOIN SystemTypesSUBDomainSPOC STSDS ON st.SystemTypeId = STSDS.SystemTypeId
JOIN SYSTEMTYPESMAJORHARDWAREBUILDS HW ON st.SystemTypeId = HW.SystemTypeId 
JOIN MAJORHARDWAREBUILDS MH ON MH.MAJORHARDWAREID = HW.MAJORHARDWAREID
JOIN SubDomainSPOCS SDS ON SDS.SubDomainSPOCID = STSDS.SubDomainSPOCID
JOIN ASPNETUSERS USR ON upper(regexp_replace(USR.email,' ','')) = upper(regexp_replace(SDS.SubDomainSPOC,' ',''))
JOIN ASPNETUSERROLES UR on USR.ID = UR.USERID
JOIN VerticalResponsibles V ON v.VerticalResponsibleid = ST.VerticalResponsibleid
JOIN BUILDCONSTRUCTIONS BC ON BC.BUILDCONSTRUCTIONID = MH.BUILDCONSTRUCTIONID  WHERE BC.BUILDCONSTRUCTION NOT IN  ('BLUEPRINT NFVI', 'OTHER NFVI', 'BLUEPRINT NFCI', 'OTHER NFCI', 'VIRTUALISED'); 
COMMIT;
